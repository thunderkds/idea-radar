import assert from "node:assert/strict";
import { describe, it } from "node:test";
import { renderTokensCss, type TokensJson } from "./tokens-css";

const tokens: TokensJson = {
  color: { tokens: [{ name: "bg", value: "#111111" }, { name: "neon", value: "#00ff99" }] },
  type: { families: { sans: '"IBM Plex Sans", sans-serif', mono: '"IBM Plex Mono", monospace' } },
  spacing: { tokens: [{ name: "space-1", value: "4px" }] },
  radius: { tokens: [{ name: "radius-sm", value: "2px" }] },
  shadow: { tokens: [{ name: "glow-neon", value: "0 0 8px #00ff99" }] },
  filter: { tokens: [{ name: "blur", value: "blur(4px)" }] },
  layout: { tokens: [{ name: "topbar-h", value: "56px" }] },
};

describe("renderTokensCss", () => {
  const css = renderTokensCss(tokens);
  it("puts every token in one :root block as a custom property", () => {
    assert.match(css, /:root \{\n/);
    for (const line of ["--bg: #111111;", "--neon: #00ff99;", "--space-1: 4px;", "--radius-sm: 2px;", "--glow-neon: 0 0 8px #00ff99;", "--blur: blur(4px);", "--topbar-h: 56px;"]) {
      assert.ok(css.includes(`  ${line}\n`), line);
    }
    assert.equal((css.match(/:root/g) ?? []).length, 1);
  });
  it("adds the two font families as --font-sans and --font-mono", () => {
    assert.match(css, /--font-sans: "IBM Plex Sans", sans-serif;/);
    assert.match(css, /--font-mono: "IBM Plex Mono", monospace;/);
  });
  it("starts with a do-not-edit header and ends with a newline", () => {
    assert.match(css, /^\/\* Generated by scripts\/gen-tokens\.ts/);
    assert.ok(css.endsWith("}\n"));
  });
  it("is deterministic", () => {
    assert.equal(renderTokensCss(tokens), css);
  });
});
